"""
Master Precomputation Pipeline Script

Acts as the master compilation compiler for the application configuration layer.
It aggregates low-level video metadata, downsamples static image thumbnails for the UI,
triggers the biomechanical calibration auto-scanner, and bakes chronological target 
trajectories into a unified deployment manifest (`master_registry.json`).
"""
import sys
import json
import cv2
from pathlib import Path

# Setup paths to ensure the runtime can locate our internal 'core' package modules
ROOT_DIR = Path(__file__).parent.parent
sys.path.append(str(ROOT_DIR))

from core.calibrator import AutoCalibrator
from core.config import VIDEOS_DIR, EXERCISE_MAP

def extract_metadata_and_thumbnail(video_path: Path, output_dir: Path) -> dict:
    """
    Extracts core physical video properties and captures a downsampled UI thumbnail.

    Opens the video file using hardware properties via OpenCV to calculate exact frame 
    rates and real-world duration. It seeks to frame index 10 (to avoid early black frames) 
    and resizes the image to a standardized width while preserving the original 
    aspect ratio.

    Args:
        video_path (Path): The pathlib Path pointing to the target MP4 asset.
        output_dir (Path): Storage directory where the JPEG thumbnail should be written.

    Returns:
        dict: A dictionary containing:
              - 'duration_sec' (float): Total length of video in seconds.
              - 'fps' (float): Frames per second property of the video stream.
              - 'thumbnail' (str): Filename string of the generated image asset.
    """
    cap = cv2.VideoCapture(str(video_path))
    
    fps = cap.get(cv2.CAP_PROP_FPS)
    frame_count = cap.get(cv2.CAP_PROP_FRAME_COUNT)
    duration_sec = frame_count / fps if fps > 0 else 0
    
    # Seek to frame 10 to capture a representative posture, bypassing zero-initializations
    cap.set(cv2.CAP_PROP_POS_FRAMES, 10)
    ret, frame = cap.read()
    
    thumbnail_filename = f"{video_path.stem}_thumb.jpg"
    thumbnail_path = output_dir / thumbnail_filename
    
    if ret:
        h, w = frame.shape[:2]
        new_w = 400
        # Preserve structural aspect ratio dynamically to avoid vertical/horizontal squashing
        new_h = int((new_w / w) * h)
        resized_frame = cv2.resize(frame, (new_w, new_h))
        cv2.imwrite(str(thumbnail_path), resized_frame)
    
    cap.release()
    
    return {
        "duration_sec": round(duration_sec, 1),
        "fps": round(fps, 2),
        "thumbnail": thumbnail_filename
    }

def get_golden_trajectory(video_id: str) -> list:
    """
    Loads raw frame-by-frame joint angle curves generated by the extraction script.

    Reads the pre-calculated sequential JSON tracking maps from the local cache and 
    extracts the mathematical angles array. This array serves as the absolute target 
    baseline for both live frame matching and post-rep Dynamic Time Warping (DTW) evaluations.

    Args:
        video_id (str): The root filename stem matching the exercise tracking file.

    Returns:
        list: A continuous collection of joint angle sub-dictionaries. Returns an 
              empty list if the dependent JSON file does not exist.
    """
    exercise_name = EXERCISE_MAP.get(f"{video_id}.mp4", video_id)
    json_path = ROOT_DIR / "data" / f"{exercise_name}.json"
    
    if json_path.exists():
        with open(json_path, "r") as f:
            data = json.load(f)
            # Isolate and extract just the calculated angular parameters per frame index
            return [frame["angles"] for frame in data]
    return []

def main():
    """
    Main entry point orchestrating the global precomputation sequence.
    
    Ensures correct subdirectory storage models exist, scans the asset directory tree 
    for target video media, layers AI analytics profiles on top of structural media properties, 
    and bakes the cumulative properties to a master registry.
    """
    print("🚀 Starting the Master Precomputation Pipeline...")
    calibrator = AutoCalibrator()
    
    data_dir = ROOT_DIR / "data"
    data_dir.mkdir(exist_ok=True)
    
    assets_dir = ROOT_DIR / "assets" 
    assets_dir.mkdir(exist_ok=True)
    
    master_registry = {}
    
    # Process all available exercise files discovered in the targets directory
    for video_path in VIDEOS_DIR.glob("*.mp4"):
        video_id = video_path.stem
        print(f"\n⚙️ Processing [{video_id}]...")
    
        print("   -> Extracting Metadata & Thumbnails...")
        meta_info = extract_metadata_and_thumbnail(video_path, assets_dir)
        
        print("   -> Running AI Biomechanical Scan...")
        physics_config = calibrator.scan_reference_video(str(video_path))
        
        if physics_config:
            print("   -> Baking Golden Trajectory for DTW Matching...")
            golden_seq = get_golden_trajectory(video_id)
            
            if not golden_seq:
                print(f"   ⚠️ Warning: No extracted JSON found for {video_id}. Run extractor.py first!")
            
            # Map the golden sequence array directly inside our active config dictionary tree
            physics_config["golden_trajectory"] = golden_seq
            
            master_registry[video_id] = {
                "display_name": video_id.replace("_", " ").title(),
                "video_file": video_path.name,
                "meta": meta_info,
                "physics": physics_config
            }
            print(f"✅ Success! Elected Joints: {physics_config.get('primary_joints')} | Trajectory Frames: {len(golden_seq)}")
        else:
            print(f"❌ AI Failed to extract motion from {video_id}")

    # Flush the consolidated master registry to the app data layer directory
    registry_path = data_dir / "master_registry.json"
    with open(registry_path, "w") as f:
        json.dump(master_registry, f, indent=4)
        
    print(f"\n🎉 Pipeline Complete! Engine is ready. Data saved to {registry_path.name}")

if __name__ == "__main__":
    main()